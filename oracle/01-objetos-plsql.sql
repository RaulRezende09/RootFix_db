-- Adota um problema: só o gestor da comunidade do problema pode.
CREATE OR REPLACE PROCEDURE PRC_ADOTAR_PROBLEMA (
    p_id_problema  IN NUMBER,
    p_id_gestor    IN NUMBER
)
IS
    v_adotado          RF_PROBLEMA.ADOTADO%TYPE;
    v_gestor_comunidade RF_COMUNIDADE.ID_GESTOR%TYPE;
BEGIN
    BEGIN
        SELECT p.ADOTADO, c.ID_GESTOR
          INTO v_adotado, v_gestor_comunidade
          FROM RF_PROBLEMA p
          JOIN RF_COMUNIDADE c ON c.ID = p.ID_COMUNIDADE
         WHERE p.ID = p_id_problema
           FOR UPDATE OF p.ADOTADO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001, 'Problema ' || p_id_problema || ' não encontrado.');
    END;

    IF p_id_gestor IS NULL OR v_gestor_comunidade != p_id_gestor THEN
        RAISE_APPLICATION_ERROR(-20002, 'Só o gestor da comunidade pode adotar este problema.');
    END IF;

    IF v_adotado = 1 THEN
        RAISE_APPLICATION_ERROR(-20003, 'O problema ' || p_id_problema || ' já foi adotado.');
    END IF;

    UPDATE RF_PROBLEMA
       SET ADOTADO    = 1,
           STATUS     = 'PENDENTE',
           ADOTADO_EM = SYSTIMESTAMP
     WHERE ID = p_id_problema;
END PRC_ADOTAR_PROBLEMA;
/

-- Altera o status de um problema adotado, validando a transição:
--   PENDENTE     -> EM_ANDAMENTO ou ARQUIVADO
--   EM_ANDAMENTO -> RESOLVIDO    ou ARQUIVADO
CREATE OR REPLACE PROCEDURE PRC_ALTERAR_STATUS (
    p_id_problema  IN NUMBER,
    p_id_gestor    IN NUMBER,
    p_status_novo  IN VARCHAR2
)
IS
    v_adotado           RF_PROBLEMA.ADOTADO%TYPE;
    v_status_atual      RF_PROBLEMA.STATUS%TYPE;
    v_gestor_comunidade RF_COMUNIDADE.ID_GESTOR%TYPE;
    v_status_novo       VARCHAR2(4000) := UPPER(TRIM(p_status_novo));

    FUNCTION transicao_permitida (p_de IN VARCHAR2, p_para IN VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        IF (p_de = 'PENDENTE'     AND p_para IN ('EM_ANDAMENTO', 'ARQUIVADO'))
        OR (p_de = 'EM_ANDAMENTO' AND p_para IN ('RESOLVIDO', 'ARQUIVADO')) THEN
            RETURN TRUE;
        END IF;
        RETURN FALSE;  -- inclui RESOLVIDO/ARQUIVADO(finais) e status atual nulo.
    END transicao_permitida;
BEGIN
    IF v_status_novo IS NULL
       OR v_status_novo NOT IN ('PENDENTE', 'EM_ANDAMENTO', 'RESOLVIDO', 'ARQUIVADO') THEN
        RAISE_APPLICATION_ERROR(-20005, 'Status inválido: ' || NVL(p_status_novo, '(vazio)') || '.');
    END IF;

    BEGIN
        SELECT p.ADOTADO, p.STATUS, c.ID_GESTOR
          INTO v_adotado, v_status_atual, v_gestor_comunidade
          FROM RF_PROBLEMA p
          JOIN RF_COMUNIDADE c ON c.ID = p.ID_COMUNIDADE
         WHERE p.ID = p_id_problema
           FOR UPDATE OF p.STATUS;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001, 'Problema ' || p_id_problema || ' não encontrado.');
    END;

    IF p_id_gestor IS NULL OR v_gestor_comunidade != p_id_gestor THEN
        RAISE_APPLICATION_ERROR(-20002, 'Só o gestor da comunidade pode alterar o status deste problema.');
    END IF;

    IF v_adotado = 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'O problema ' || p_id_problema || ' ainda não foi adotado.');
    END IF;

    IF NOT transicao_permitida(v_status_atual, v_status_novo) THEN
        RAISE_APPLICATION_ERROR(-20006,
            'Não é permitido mudar o status de ' || v_status_atual || ' para ' || v_status_novo || '.');
    END IF;

    UPDATE RF_PROBLEMA
       SET STATUS = v_status_novo
     WHERE ID = p_id_problema;
END PRC_ALTERAR_STATUS;
/


