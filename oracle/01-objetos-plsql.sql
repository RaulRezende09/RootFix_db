-- PKG_COMUNIDADE: proximidade (regra dos 3 km) e membros.
CREATE OR REPLACE PACKAGE PKG_COMUNIDADE AS
    c_raio_km CONSTANT NUMBER := 3;

    -- Distância em km entre dois pontos - *usa FN_DISTANCIA_KM.
    FUNCTION distancia_km (p_lat1 NUMBER, p_lon1 NUMBER, p_lat2 NUMBER, p_lon2 NUMBER) RETURN NUMBER;

    -- Quantidade de moradores que participam da comunidade.
    FUNCTION total_membros (p_id_comunidade NUMBER) RETURN NUMBER;

    -- 1 se a comunidade está a até 3 km do endereço do usuário, 0 se não.
    FUNCTION esta_no_raio (p_id_usuario NUMBER, p_id_comunidade NUMBER) RETURN NUMBER;

    -- Comunidades a até 3 km do usuário, da mais perto para a mais longe.
    -- Colunas: ID, NOME, GESTOR, ORGANIZACAO, DIST_KM.
    FUNCTION comunidades_proximas (p_id_usuario NUMBER) RETURN SYS_REFCURSOR;

    -- Mostra as comunidades próximas com DBMS_OUTPUT.
    PROCEDURE listar_proximas (p_id_usuario NUMBER);
END PKG_COMUNIDADE;
/

CREATE OR REPLACE PACKAGE BODY PKG_COMUNIDADE AS

    FUNCTION distancia_km (p_lat1 NUMBER, p_lon1 NUMBER, p_lat2 NUMBER, p_lon2 NUMBER) RETURN NUMBER IS
    BEGIN
        RETURN FN_DISTANCIA_KM(p_lat1, p_lon1, p_lat2, p_lon2);
    END distancia_km;

    FUNCTION total_membros (p_id_comunidade NUMBER) RETURN NUMBER IS
        v_total NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO v_total
          FROM RF_PARTICIPACAO
         WHERE ID_COMUNIDADE = p_id_comunidade;
        RETURN v_total;
    END total_membros;

    FUNCTION esta_no_raio (p_id_usuario NUMBER, p_id_comunidade NUMBER) RETURN NUMBER IS
        v_lat_u  RF_USUARIO.LATITUDE%TYPE;
        v_lon_u  RF_USUARIO.LONGITUDE%TYPE;
        v_lat_c  RF_COMUNIDADE.LATITUDE%TYPE;
        v_lon_c  RF_COMUNIDADE.LONGITUDE%TYPE;
    BEGIN
        BEGIN
            SELECT LATITUDE, LONGITUDE INTO v_lat_u, v_lon_u FROM RF_USUARIO WHERE ID = p_id_usuario;
            SELECT LATITUDE, LONGITUDE INTO v_lat_c, v_lon_c FROM RF_COMUNIDADE WHERE ID = p_id_comunidade;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20008, 'Usuário ou comunidade não encontrado.');
        END;

        IF v_lat_u IS NULL OR v_lon_u IS NULL THEN
            RETURN 0;  -- gestor sem endereço cadastrado
        END IF;

        IF distancia_km(v_lat_u, v_lon_u, v_lat_c, v_lon_c) <= c_raio_km THEN
            RETURN 1;
        END IF;
        RETURN 0;
    END esta_no_raio;

    FUNCTION comunidades_proximas (p_id_usuario NUMBER) RETURN SYS_REFCURSOR IS
        v_cursor SYS_REFCURSOR;
    BEGIN
        OPEN v_cursor FOR
            SELECT c.ID,
                   c.NOME,
                   g.NOME        AS GESTOR,
                   g.ORGANIZACAO,
                   ROUND(FN_DISTANCIA_KM(u.LATITUDE, u.LONGITUDE, c.LATITUDE, c.LONGITUDE), 2) AS DIST_KM
              FROM RF_COMUNIDADE c
              JOIN RF_USUARIO g ON g.ID = c.ID_GESTOR
             CROSS JOIN (SELECT LATITUDE, LONGITUDE FROM RF_USUARIO WHERE ID = p_id_usuario) u
             WHERE FN_DISTANCIA_KM(u.LATITUDE, u.LONGITUDE, c.LATITUDE, c.LONGITUDE) <= c_raio_km
             ORDER BY DIST_KM;
        RETURN v_cursor;
    END comunidades_proximas;

    PROCEDURE listar_proximas (p_id_usuario NUMBER) IS
        v_cursor       SYS_REFCURSOR;
        v_id           RF_COMUNIDADE.ID%TYPE;
        v_nome         RF_COMUNIDADE.NOME%TYPE;
        v_gestor       RF_USUARIO.NOME%TYPE;
        v_organizacao  RF_USUARIO.ORGANIZACAO%TYPE;
        v_distancia    NUMBER;
        v_qtd          PLS_INTEGER := 0;
    BEGIN
        v_cursor := comunidades_proximas(p_id_usuario);
        LOOP
            FETCH v_cursor INTO v_id, v_nome, v_gestor, v_organizacao, v_distancia;
            EXIT WHEN v_cursor%NOTFOUND;
            v_qtd := v_qtd + 1;
            DBMS_OUTPUT.PUT_LINE('  ' || v_nome || ' (' || TO_CHAR(v_distancia, 'FM990.00') || ' km) - gestor: '
                                 || v_gestor || ', ' || v_organizacao);
        END LOOP;
        CLOSE v_cursor;

        IF v_qtd = 0 THEN
            DBMS_OUTPUT.PUT_LINE('  Nenhuma comunidade a até ' || c_raio_km || ' km.');
        END IF;
    END listar_proximas;

END PKG_COMUNIDADE;
/

-- PKG_PROBLEMA: apoios, adoção, status e rankings.
CREATE OR REPLACE PACKAGE PKG_PROBLEMA AS
    -- Total de apoios de um problema - *usa FN_TOTAL_APOIOS
    FUNCTION total_apoios (p_id_problema NUMBER) RETURN NUMBER;

    -- Adota o problema - *usa PRC_ADOTAR_PROBLEMA
    PROCEDURE adotar (p_id_problema NUMBER, p_id_gestor NUMBER);

    -- Altera o status validando a transição - *usa PRC_ALTERAR_STATUS
    PROCEDURE alterar_status (p_id_problema NUMBER, p_id_gestor NUMBER, p_status_novo VARCHAR2);

    -- Quantos problemas da comunidade estão em um status.
    -- p_status NULL conta os que ainda estão só no feed - (não adotados).
    FUNCTION total_por_status (p_id_comunidade NUMBER, p_status VARCHAR2) RETURN NUMBER;

    -- Mostra os problemas mais apoiados da comunidade com DBMS_OUTPUT
    PROCEDURE listar_mais_apoiados (p_id_comunidade NUMBER, p_quantidade NUMBER DEFAULT 3);
END PKG_PROBLEMA;
/

CREATE OR REPLACE PACKAGE BODY PKG_PROBLEMA AS

    FUNCTION total_apoios (p_id_problema NUMBER) RETURN NUMBER IS
    BEGIN
        RETURN FN_TOTAL_APOIOS(p_id_problema);
    END total_apoios;

    PROCEDURE adotar (p_id_problema NUMBER, p_id_gestor NUMBER) IS
    BEGIN
        PRC_ADOTAR_PROBLEMA(p_id_problema, p_id_gestor);
    END adotar;

    PROCEDURE alterar_status (p_id_problema NUMBER, p_id_gestor NUMBER, p_status_novo VARCHAR2) IS
    BEGIN
        PRC_ALTERAR_STATUS(p_id_problema, p_id_gestor, p_status_novo);
    END alterar_status;

    FUNCTION total_por_status (p_id_comunidade NUMBER, p_status VARCHAR2) RETURN NUMBER IS
        v_total NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO v_total
          FROM RF_PROBLEMA
         WHERE ID_COMUNIDADE = p_id_comunidade
           AND ((p_status IS NULL AND ADOTADO = 0)
                OR STATUS = UPPER(p_status));
        RETURN v_total;
    END total_por_status;

    PROCEDURE listar_mais_apoiados (p_id_comunidade NUMBER, p_quantidade NUMBER DEFAULT 3) IS
        v_posicao PLS_INTEGER := 0;
    BEGIN
        FOR r IN (SELECT p.TITULO,
                         NVL(p.STATUS, 'NO FEED') AS SITUACAO,
                         COUNT(a.ID)              AS APOIOS
                    FROM RF_PROBLEMA p
                    LEFT JOIN RF_APOIO a ON a.ID_PROBLEMA = p.ID
                   WHERE p.ID_COMUNIDADE = p_id_comunidade
                   GROUP BY p.ID, p.TITULO, p.STATUS, p.CRIADO_EM
                   ORDER BY APOIOS DESC, p.CRIADO_EM
                   FETCH FIRST p_quantidade ROWS ONLY)
        LOOP
            v_posicao := v_posicao + 1;
            DBMS_OUTPUT.PUT_LINE('    ' || v_posicao || '. ' || r.TITULO || ' - ' || r.APOIOS
                                 || ' apoio(s) - ' || r.SITUACAO);
        END LOOP;

        IF v_posicao = 0 THEN
            DBMS_OUTPUT.PUT_LINE('    Nenhum problema publicado.');
        END IF;
    END listar_mais_apoiados;

END PKG_PROBLEMA;
/

