-- Distância em km entre dois pontos (fórmula de Haversine).
-- Devolve NULL se faltar alguma coordenada.
CREATE OR REPLACE FUNCTION FN_DISTANCIA_KM (
    p_lat1  IN NUMBER,
    p_lon1  IN NUMBER,
    p_lat2  IN NUMBER,
    p_lon2  IN NUMBER
) RETURN NUMBER
DETERMINISTIC
IS
    c_raio_terra_km CONSTANT NUMBER := 6371;
    c_grau_rad      CONSTANT NUMBER := ACOS(-1) / 180;   -- pi / 180
    v_dlat  NUMBER;
    v_dlon  NUMBER;
    v_a     NUMBER;
BEGIN
    IF p_lat1 IS NULL OR p_lon1 IS NULL OR p_lat2 IS NULL OR p_lon2 IS NULL THEN
        RETURN NULL;
    END IF;

    v_dlat := (p_lat2 - p_lat1) * c_grau_rad;
    v_dlon := (p_lon2 - p_lon1) * c_grau_rad;

    v_a := POWER(SIN(v_dlat / 2), 2)
         + COS(p_lat1 * c_grau_rad) * COS(p_lat2 * c_grau_rad) * POWER(SIN(v_dlon / 2), 2);
    v_a := LEAST(1, GREATEST(0, v_a));  -- evita raiz de número negativo por arredondamento

    RETURN 2 * c_raio_terra_km * ATAN2(SQRT(v_a), SQRT(1 - v_a));
END FN_DISTANCIA_KM;
/

-- Total de apoios de um problema - *Problema inexistente devolve 0.
CREATE OR REPLACE FUNCTION FN_TOTAL_APOIOS (
    p_id_problema IN NUMBER
) RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_total
      FROM RF_APOIO
     WHERE ID_PROBLEMA = p_id_problema;

    RETURN v_total;
END FN_TOTAL_APOIOS;
