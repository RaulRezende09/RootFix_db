-- Auditoria: uma linha por INSERT, UPDATE ou DELETE em RF_PROBLEMA.
CREATE OR REPLACE TRIGGER TRG_RF_PROBLEMA_AUDITORIA
AFTER INSERT OR UPDATE OR DELETE ON RF_PROBLEMA
FOR EACH ROW
DECLARE
    v_operacao  VARCHAR2(6);
    v_antigo    VARCHAR2(32767);
    v_novo      VARCHAR2(32767);
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
    ELSE
        v_operacao := 'DELETE';
    END IF;

    IF NOT INSERTING THEN
        v_antigo := 'titulo=' || :OLD.TITULO
                 || '; descricao=' || SUBSTR(:OLD.DESCRICAO, 1, 200)
                 || '; id_categoria=' || NVL(TO_CHAR(:OLD.ID_CATEGORIA), 'null')
                 || '; adotado=' || :OLD.ADOTADO
                 || '; adotado_em=' || NVL(TO_CHAR(:OLD.ADOTADO_EM, 'YYYY-MM-DD HH24:MI:SS'), 'null')
                 || '; status=' || NVL(:OLD.STATUS, 'null')
                 || '; prioridade=' || NVL(:OLD.PRIORIDADE, 'null')
                 || '; gravidade_ia=' || NVL(:OLD.GRAVIDADE_IA, 'null');
    END IF;

    IF NOT DELETING THEN
        v_novo := 'titulo=' || :NEW.TITULO
               || '; descricao=' || SUBSTR(:NEW.DESCRICAO, 1, 200)
               || '; id_categoria=' || NVL(TO_CHAR(:NEW.ID_CATEGORIA), 'null')
               || '; adotado=' || :NEW.ADOTADO
               || '; adotado_em=' || NVL(TO_CHAR(:NEW.ADOTADO_EM, 'YYYY-MM-DD HH24:MI:SS'), 'null')
               || '; status=' || NVL(:NEW.STATUS, 'null')
               || '; prioridade=' || NVL(:NEW.PRIORIDADE, 'null')
               || '; gravidade_ia=' || NVL(:NEW.GRAVIDADE_IA, 'null');
    END IF;

    INSERT INTO RF_AUDITORIA_PROBLEMA (ID_PROBLEMA, OPERACAO, VALOR_ANTIGO, VALOR_NOVO)
    VALUES (NVL(:NEW.ID, :OLD.ID), v_operacao, SUBSTRB(v_antigo, 1, 4000), SUBSTRB(v_novo, 1, 4000));
EXCEPTION
    -- A auditoria nunca pode derrubar uma gravação das APIs Java e .NET.
    WHEN OTHERS THEN
        NULL;
END TRG_RF_PROBLEMA_AUDITORIA;
/

-- Adoção: quando ADOTADO vira 1, garante a data de adoção e o status inicial.
-- Só preenche o que veio vazio e não sobrescreve o que a API ou o procedimento já mandaram.
CREATE OR REPLACE TRIGGER TRG_RF_PROBLEMA_ADOCAO
BEFORE UPDATE OF ADOTADO ON RF_PROBLEMA
FOR EACH ROW
WHEN (NEW.ADOTADO = 1 AND OLD.ADOTADO = 0)
BEGIN
    IF :NEW.ADOTADO_EM IS NULL THEN
        :NEW.ADOTADO_EM := SYSTIMESTAMP;
    END IF;

    IF :NEW.STATUS IS NULL THEN
        :NEW.STATUS := 'PENDENTE';
    END IF;
END TRG_RF_PROBLEMA_ADOCAO;
/


